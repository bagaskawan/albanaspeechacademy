create table if not exists public.inhouse_gallery (
  id bigint generated by default as identity primary key,
  title text,
  image_url text not null,
  consent_at timestamptz not null default now(),
  consent_verified_at timestamptz
);

alter table public.inhouse_gallery enable row level security;

drop policy if exists inhouse_gallery_public on public.inhouse_gallery;
create policy inhouse_gallery_public on public.inhouse_gallery
  for select to anon, authenticated
  using (consent_verified_at is not null);

drop policy if exists inhouse_gallery_admin_write on public.inhouse_gallery;
create policy inhouse_gallery_admin_write on public.inhouse_gallery
  for all to authenticated
  using (exists (select 1 from public.admin_users a where a.user_id = (select auth.uid())))
  with check (exists (select 1 from public.admin_users a where a.user_id = (select auth.uid())));

grant select on public.inhouse_gallery to anon;
grant select, insert, update, delete on public.inhouse_gallery to authenticated;
grant all on public.inhouse_gallery to service_role;

insert into storage.buckets (id, name, public)
values ('inhouse-gallery', 'inhouse-gallery', true)
on conflict (id) do nothing;

drop policy if exists inhouse_gallery_public_select on storage.objects;
create policy inhouse_gallery_public_select on storage.objects
  for select to anon, authenticated
  using (bucket_id = 'inhouse-gallery');

drop policy if exists inhouse_gallery_admin_insert on storage.objects;
create policy inhouse_gallery_admin_insert on storage.objects
  for insert to authenticated
  with check (
    bucket_id = 'inhouse-gallery'
    and exists (select 1 from public.admin_users a where a.user_id = auth.uid())
  );

drop policy if exists inhouse_gallery_admin_update on storage.objects;
create policy inhouse_gallery_admin_update on storage.objects
  for update to authenticated
  using (
    bucket_id = 'inhouse-gallery'
    and exists (select 1 from public.admin_users a where a.user_id = auth.uid())
  );

drop policy if exists inhouse_gallery_admin_delete on storage.objects;
create policy inhouse_gallery_admin_delete on storage.objects
  for delete to authenticated
  using (
    bucket_id = 'inhouse-gallery'
    and exists (select 1 from public.admin_users a where a.user_id = auth.uid())
  );

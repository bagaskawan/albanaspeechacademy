"use client";

import { useEffect, useRef, useState, useTransition } from "react";
import { useRouter } from "next/navigation";
import { Check, ImagePlus, Loader2, Pencil, Play, Plus, RefreshCw, Trash2, UploadCloud, X } from "lucide-react";
import { toast } from "sonner";
import { DeleteSheet } from "@/components/admin/ui/delete-sheet";
import { UploadBlockingModal } from "@/components/admin/ui/UploadBlockingModal";
import { AdminInput } from "@/components/admin/ui/form/controls";
import { Field, FieldGrid } from "@/components/admin/ui/form/fields";
import {
  addProgramVideo,
  fetchYouTubeTitle,
  removeMultipleProgramMedia,
  removeProgramMedia,
  updateProgramVideo,
} from "@/app/(admin)/admin/program/actions";
import {
  MAX_PROGRAM_PHOTOS,
  MAX_PROGRAM_VIDEOS,
  mediaCapacity,
  photoLimitError,
  type ProgramMediaItem,
} from "@/lib/program-media";
import { youtubeVideoId } from "@/lib/youtube";

type VideoDraft = {
  id: string;
  url: string;
  title: string;
  autoGenerated: boolean;
  fetching: boolean;
};

type EditingVideo = {
  id: number;
  url: string;
  title: string;
  autoGenerated: boolean;
  fetching: boolean;
};

function createEmptyVideoDraft(): VideoDraft {
  return {
    id: typeof crypto !== "undefined" && typeof crypto.randomUUID === "function"
      ? crypto.randomUUID()
      : `${Date.now()}-${Math.random().toString(36).slice(2)}`,
    url: "",
    title: "",
    autoGenerated: false,
    fetching: false,
  };
}

type StagedPhoto = {
  id: string;
  programSlug: string;
  file: File;
  previewUrl: string;
  altText: string;
};

const MAX_STAGED_IMAGE_BYTES = 10 * 1024 * 1024;

export function ProgramMediaEditor({
  programSlug,
  items,
  formId = "program-media-editor-form",
  hideInlineSubmit = false,
  onSubmitSuccess,
}: {
  programSlug: string;
  items: ProgramMediaItem[];
  formId?: string;
  hideInlineSubmit?: boolean;
  onSubmitSuccess?: () => void;
}) {
  const router = useRouter();
  const fileRef = useRef<HTMLInputElement>(null);
  const replaceSingleRef = useRef<HTMLInputElement>(null);
  const replaceMultiRef = useRef<HTMLInputElement>(null);
  const [altText, setAltText] = useState("");
  const [isDragging, setIsDragging] = useState(false);
  const [queuedPhotos, setQueuedPhotos] = useState<StagedPhoto[]>([]);
  const queuedRef = useRef<StagedPhoto[]>([]);
  const [uploadProgress, setUploadProgress] = useState<{ current: number; total: number } | null>(null);
  const [uploadErrors, setUploadErrors] = useState<string[]>([]);
  const [videoDrafts, setVideoDrafts] = useState<VideoDraft[]>(() => [createEmptyVideoDraft()]);
  const [editingVideo, setEditingVideo] = useState<EditingVideo | null>(null);
  const [videoError, setVideoError] = useState<string | null>(null);
  const videoTitleTimersRef = useRef<Map<string, ReturnType<typeof setTimeout>>>(new Map());
  const [deleteTarget, setDeleteTarget] = useState<ProgramMediaItem | null>(null);
  const [replaceTargetId, setReplaceTargetId] = useState<number | null>(null);
  const [selectedPhotoIds, setSelectedPhotoIds] = useState<number[]>([]);
  const [confirmMultiDelete, setConfirmMultiDelete] = useState(false);
  const [replacedVersions, setReplacedVersions] = useState<Record<number, number>>({});
  const [isPending, startTransition] = useTransition();

  const photos = items.filter((item) => item.kind === "image");
  const videos = items.filter((item) => item.kind === "video");
  const cap = mediaCapacity(items);
  const activeQueue = queuedPhotos.filter((item) => item.programSlug === programSlug);
  const totalWithQueue = cap.photos + activeQueue.length;
  const remainingQueueSlots = Math.max(0, MAX_PROGRAM_PHOTOS - totalWithQueue);
  const queueOrPhotoFull = remainingQueueSlots === 0;

  useEffect(() => {
    queuedRef.current = queuedPhotos;
  }, [queuedPhotos]);

  useEffect(() => {
    const timers = videoTitleTimersRef.current;
    return () => {
      for (const item of queuedRef.current) {
        URL.revokeObjectURL(item.previewUrl);
      }
      for (const timer of timers.values()) {
        clearTimeout(timer);
      }
      timers.clear();
    };
  }, []);

  function stageFiles(selected: File[]) {
    if (selected.length === 0 || uploadProgress !== null) return;

    const acceptedTypes = new Set(["image/jpeg", "image/png", "image/webp"]);
    const errors: string[] = [];
    const validFiles: File[] = [];
    let skippedTypeCount = 0;

    for (const file of selected) {
      if (!acceptedTypes.has(file.type)) {
        skippedTypeCount += 1;
        continue;
      }
      if (file.size < 1 || file.size > MAX_STAGED_IMAGE_BYTES) {
        errors.push(`${file.name}: Ukuran file maksimal 10 MiB.`);
        continue;
      }
      validFiles.push(file);
    }

    if (skippedTypeCount > 0) {
      errors.push(`${skippedTypeCount} berkas bukan JPEG/PNG/WebP dilewati.`);
    }

    if (validFiles.length === 0) {
      setUploadErrors(errors.length > 0 ? errors : ["Gunakan berkas gambar JPEG, PNG, atau WebP."]);
      return;
    }

    if (remainingQueueSlots === 0) {
      setUploadErrors([`Batas ${MAX_PROGRAM_PHOTOS} foto sudah tercapai (termasuk foto di antrean).`]);
      return;
    }

    let filesToStage = validFiles;
    if (validFiles.length > remainingQueueSlots) {
      filesToStage = validFiles.slice(0, remainingQueueSlots);
      errors.push(`Hanya ${remainingQueueSlots} foto lagi yang bisa ditambahkan; ${validFiles.length - filesToStage.length} berkas dilewati.`);
    }
    const limitErr = photoLimitError(totalWithQueue, filesToStage.length);
    if (limitErr) {
      setUploadErrors([limitErr]);
      return;
    }

    const cleanAlt = altText.trim();
    const staged: StagedPhoto[] = filesToStage.map((file) => {
      const fallbackAlt = file.name.replace(/\.[^.]+$/, "").replace(/[-_]+/g, " ").trim() || "Dokumentasi program";
      return {
        id: typeof crypto !== "undefined" && typeof crypto.randomUUID === "function"
          ? crypto.randomUUID()
          : `${Date.now()}-${Math.random().toString(36).slice(2)}`,
        programSlug,
        file,
        previewUrl: URL.createObjectURL(file),
        altText: cleanAlt || fallbackAlt,
      };
    });

    setUploadErrors(errors);
    setQueuedPhotos((prev) => {
      const kept: StagedPhoto[] = [];
      for (const item of prev) {
        if (item.programSlug === programSlug) {
          kept.push(item);
        } else {
          URL.revokeObjectURL(item.previewUrl);
        }
      }
      return [...kept, ...staged];
    });
  }

  function removeQueuedPhoto(id: string) {
    if (uploadProgress !== null) return;
    setQueuedPhotos((prev) => {
      const target = prev.find((item) => item.id === id);
      if (target) URL.revokeObjectURL(target.previewUrl);
      return prev.filter((item) => item.id !== id);
    });
  }

  function clearQueuedPhotos() {
    if (uploadProgress !== null) return;
    setQueuedPhotos((prev) => {
      for (const item of prev) URL.revokeObjectURL(item.previewUrl);
      return [];
    });
    setUploadErrors([]);
  }

  async function submitQueuedPhotos(): Promise<{ uploadedCount: number; hasErrors: boolean }> {
    if (activeQueue.length === 0 || uploadProgress !== null) return { uploadedCount: 0, hasErrors: false };

    const batch = [...activeQueue];
    const errors: string[] = [];
    let uploadedCount = 0;

    setUploadErrors([]);

    for (let i = 0; i < batch.length; i += 1) {
      const item = batch[i];
      setUploadProgress({ current: i + 1, total: batch.length });
      const body = new FormData();
      body.set("purpose", "program");
      body.set("programSlug", programSlug);
      body.set("altText", item.altText);
      body.set("file", item.file);

      try {
        const res = await fetch("/api/upload", { method: "POST", body });
        const data = (await res.json().catch(() => ({}))) as { error?: string };
        if (!res.ok) {
          errors.push(`${item.file.name}: ${data.error || "Gagal mengunggah."}`);
        } else {
          uploadedCount += 1;
          URL.revokeObjectURL(item.previewUrl);
          setQueuedPhotos((prev) => prev.filter((q) => q.id !== item.id));
        }
      } catch {
        errors.push(`${item.file.name}: Gagal terhubung ke server.`);
      }
    }

    setUploadProgress(null);
    setUploadErrors(errors);
    return { uploadedCount, hasErrors: errors.length > 0 };
  }

  function handleFilesSelected(e: React.ChangeEvent<HTMLInputElement>) {
    const selected = Array.from(e.target.files ?? []);
    e.target.value = "";
    stageFiles(selected);
  }

  async function replacePhotos(targetIds: number[], selected: File[]) {
    if (targetIds.length === 0 || selected.length === 0 || uploadProgress !== null) return;
    const acceptedTypes = new Set(["image/jpeg", "image/png", "image/webp"]);
    const validFiles = selected.filter((file) => acceptedTypes.has(file.type));
    if (validFiles.length === 0) {
      setUploadErrors(["Gunakan berkas gambar JPEG, PNG, atau WebP."]);
      return;
    }

    const pairCount = Math.min(targetIds.length, validFiles.length);
    const errors: string[] = [];
    if (validFiles.length > targetIds.length) {
      errors.push(`Hanya ${targetIds.length} foto yang dipilih untuk diganti; ${validFiles.length - targetIds.length} berkas dilewati.`);
    }
    setUploadErrors(errors);

    const cleanAlt = altText.trim();
    let replacedCount = 0;

    for (let i = 0; i < pairCount; i += 1) {
      const assetId = targetIds[i];
      const file = validFiles[i];
      setUploadProgress({ current: i + 1, total: pairCount });

      const body = new FormData();
      body.set("purpose", "program");
      body.set("programSlug", programSlug);
      body.set("replaceAssetId", String(assetId));
      if (cleanAlt) body.set("altText", cleanAlt);
      body.set("file", file);

      try {
        const res = await fetch("/api/upload", { method: "POST", body });
        const data = (await res.json().catch(() => ({}))) as { error?: string };
        if (!res.ok) {
          errors.push(`${file.name}: ${data.error || "Gagal mengganti foto."}`);
        } else {
          replacedCount += 1;
          setReplacedVersions((prev) => ({ ...prev, [assetId]: Date.now() }));
        }
      } catch {
        errors.push(`${file.name}: Gagal terhubung ke server.`);
      }
    }

    setUploadProgress(null);
    setUploadErrors([...errors]);
    if (replacedCount > 0) {
      setSelectedPhotoIds([]);
      toast.success(`${replacedCount} foto berhasil diganti dan file lama dihapus.`);
      router.refresh();
    }
  }

  function togglePhotoSelection(id: number) {
    setSelectedPhotoIds((prev) =>
      prev.includes(id) ? prev.filter((item) => item !== id) : [...prev, id]
    );
  }

  async function confirmMultiDeleteAction() {
    const res = await removeMultipleProgramMedia([...selectedPhotoIds]);
    if (!res.error) setSelectedPhotoIds([]);
    return res;
  }

  function handleDrop(e: React.DragEvent<HTMLDivElement>) {
    e.preventDefault();
    e.stopPropagation();
    setIsDragging(false);
    if (queueOrPhotoFull || uploadProgress !== null) return;
    const dropped = Array.from(e.dataTransfer.files ?? []);
    stageFiles(dropped);
  }

  const visibleVideoDrafts = cap.videoFull ? [] : videoDrafts.slice(0, cap.videoSlotsLeft);

  function scheduleDraftTitleFetch(draftId: string, url: string, force = false) {
    const timers = videoTitleTimersRef.current;
    const prevTimer = timers.get(draftId);
    if (prevTimer) clearTimeout(prevTimer);

    const trimmed = url.trim();
    if (!youtubeVideoId(trimmed)) return;

    const timer = setTimeout(async () => {
      timers.delete(draftId);
      setVideoDrafts((prev) =>
        prev.map((d) => (d.id === draftId ? { ...d, fetching: true } : d))
      );
      const res = await fetchYouTubeTitle(trimmed);
      setVideoDrafts((prev) =>
        prev.map((d) => {
          if (d.id !== draftId) return d;
          if (res.title && (force || !d.title.trim() || d.autoGenerated)) {
            return { ...d, title: res.title, autoGenerated: true, fetching: false };
          }
          return { ...d, fetching: false };
        })
      );
      if (force && res.error) {
        setVideoError(res.error);
      }
    }, force ? 0 : 400);

    timers.set(draftId, timer);
  }

  function scheduleEditTitleFetch(url: string, force = false) {
    const timers = videoTitleTimersRef.current;
    const prevTimer = timers.get("__edit__");
    if (prevTimer) clearTimeout(prevTimer);

    const trimmed = url.trim();
    if (!youtubeVideoId(trimmed)) return;

    const timer = setTimeout(async () => {
      timers.delete("__edit__");
      setEditingVideo((prev) => (prev ? { ...prev, fetching: true } : prev));
      const res = await fetchYouTubeTitle(trimmed);
      setEditingVideo((prev) => {
        if (!prev) return prev;
        if (res.title && (force || !prev.title.trim() || prev.autoGenerated)) {
          return { ...prev, title: res.title, autoGenerated: true, fetching: false };
        }
        return { ...prev, fetching: false };
      });
      if (force && res.error) {
        setVideoError(res.error);
      }
    }, force ? 0 : 400);

    timers.set("__edit__", timer);
  }

  function handleAddVideoDraftRow() {
    if (visibleVideoDrafts.length >= cap.videoSlotsLeft) return;
    setVideoError(null);
    setVideoDrafts((prev) => [...prev.slice(0, cap.videoSlotsLeft), createEmptyVideoDraft()]);
  }

  function handleRemoveVideoDraftRow(draftId: string) {
    const timers = videoTitleTimersRef.current;
    const prevTimer = timers.get(draftId);
    if (prevTimer) {
      clearTimeout(prevTimer);
      timers.delete(draftId);
    }
    setVideoDrafts((prev) => {
      const next = prev.filter((d) => d.id !== draftId);
      return next.length > 0 ? next : [createEmptyVideoDraft()];
    });
  }

  async function handleSubmitAll(e: React.FormEvent) {
    e.preventDefault();
    if (uploadProgress !== null || isPending) return;

    const filledVideos = visibleVideoDrafts.filter((d) => d.url.trim() !== "");
    const hasPhotos = activeQueue.length > 0;
    const hasVideos = filledVideos.length > 0;
    const hasEditingVideo = editingVideo !== null;

    if (!hasPhotos && !hasVideos && !hasEditingVideo) {
      toast.info("Belum ada foto atau video baru untuk disimpan.");
      return;
    }

    setVideoError(null);
    let savedPhotoCount = 0;
    let photoHasErrors = false;
    let savedVideoCount = 0;
    let updatedVideo = false;
    let videoHasErrors = false;

    if (hasPhotos) {
      const photoRes = await submitQueuedPhotos();
      savedPhotoCount = photoRes.uploadedCount;
      photoHasErrors = photoRes.hasErrors;
    }

    if (hasVideos || hasEditingVideo) {
      startTransition(async () => {
        if (hasEditingVideo && editingVideo) {
          const res = await updateProgramVideo({
            id: editingVideo.id,
            url: editingVideo.url,
            title: editingVideo.title,
          });
          if (res.error) {
            setVideoError(res.error);
            videoHasErrors = true;
          } else {
            updatedVideo = true;
            setEditingVideo(null);
          }
        }

        if (hasVideos) {
          const remaining: VideoDraft[] = [];
          for (const draft of filledVideos) {
            const res = await addProgramVideo({
              programSlug,
              url: draft.url,
              title: draft.title,
            });
            if (res.error) {
              setVideoError(res.error);
              videoHasErrors = true;
              remaining.push(draft);
            } else {
              savedVideoCount += 1;
            }
          }
          setVideoDrafts(remaining.length > 0 ? remaining : [createEmptyVideoDraft()]);
        }

        const messages: string[] = [];
        if (savedPhotoCount > 0) messages.push(`${savedPhotoCount} foto`);
        if (savedVideoCount > 0) messages.push(`${savedVideoCount} video`);
        if (updatedVideo) messages.push("perubahan video");
        if (messages.length > 0) {
          toast.success(`${messages.join(" dan ")} berhasil disimpan.`);
          router.refresh();
          if (!photoHasErrors && !videoHasErrors) {
            onSubmitSuccess?.();
          }
        }
      });
    } else if (savedPhotoCount > 0) {
      toast.success(`${savedPhotoCount} foto berhasil disimpan.`);
      router.refresh();
      if (!photoHasErrors) {
        onSubmitSuccess?.();
      }
    }
  }

  function handleSaveEditedVideo() {
    if (!editingVideo) return;
    setVideoError(null);
    const target = editingVideo;
    startTransition(async () => {
      const res = await updateProgramVideo({ id: target.id, url: target.url, title: target.title });
      if (res.error) {
        setVideoError(res.error);
        return;
      }
      setEditingVideo(null);
      toast.success("Video YouTube diperbarui.");
      router.refresh();
    });
  }

  async function confirmDelete() {
    if (!deleteTarget) return;
    return removeProgramMedia(deleteTarget.id);
  }

  return (
    <form id={formId} onSubmit={handleSubmitAll} className="space-y-8">
      <p className="text-[13px] text-admin-text-secondary">
        10–20 foto dan 1–2 video YouTube. Foto otomatis dikompresi ke WebP.
      </p>

      {/* Foto */}
      <div className="space-y-4">
        <div className="flex flex-wrap items-center justify-between gap-3">
          <div className="flex flex-wrap items-center gap-2.5">
            <h3 className="text-[14px] font-semibold text-admin-ink">
              Foto{" "}
              <span className={cap.photosBelowMin ? "text-admin-peach-ink" : "text-admin-text-secondary"}>
                {cap.photos} / {MAX_PROGRAM_PHOTOS}
              </span>
            </h3>
            {cap.photosBelowMin && (
              <span className="rounded-full bg-admin-peach-soft px-2.5 py-0.5 text-[12px] font-medium text-admin-peach-ink">
                Disarankan minimal 10 foto
              </span>
            )}
          </div>
          <button
            type="button"
            disabled={queueOrPhotoFull || uploadProgress !== null}
            onClick={() => fileRef.current?.click()}
            className="inline-flex h-10 items-center justify-center gap-2 rounded-full bg-admin-ink px-4 text-[13px] font-medium text-admin-on-ink transition-colors hover:bg-admin-ink-soft disabled:cursor-not-allowed disabled:opacity-50"
          >
            {uploadProgress ? (
              <>
                <Loader2 aria-hidden="true" size={15} className="animate-spin" />
                <span>
                  Mengunggah {uploadProgress.current} dari {uploadProgress.total}…
                </span>
              </>
            ) : (
              <>
                <ImagePlus aria-hidden="true" size={15} />
                <span>+ Pilih foto</span>
              </>
            )}
          </button>
          <input
            ref={fileRef}
            type="file"
            multiple
            accept="image/jpeg,image/png,image/webp"
            className="sr-only"
            onChange={handleFilesSelected}
          />
          <input
            ref={replaceSingleRef}
            type="file"
            accept="image/jpeg,image/png,image/webp"
            className="sr-only"
            onChange={(e) => {
              const file = e.target.files?.[0];
              const targetId = replaceTargetId;
              e.target.value = "";
              setReplaceTargetId(null);
              if (file && targetId !== null) {
                void replacePhotos([targetId], [file]);
              }
            }}
          />
          <input
            ref={replaceMultiRef}
            type="file"
            multiple
            accept="image/jpeg,image/png,image/webp"
            className="sr-only"
            onChange={(e) => {
              const files = Array.from(e.target.files ?? []);
              e.target.value = "";
              if (files.length > 0 && selectedPhotoIds.length > 0) {
                void replacePhotos(selectedPhotoIds, files);
              }
            }}
          />
        </div>

        <FieldGrid columns={1}>
          <Field
            label="Keterangan gambar (opsional)"
            htmlFor="program-media-alt"
            hint="Jika dikosongkan, nama file digunakan otomatis sebagai keterangan."
          >
            <AdminInput
              id="program-media-alt"
              type="text"
              value={altText}
              onChange={(e) => setAltText(e.target.value)}
              placeholder="Misal: Suasana praktik Public Speaking Series"
              maxLength={500}
            />
          </Field>
        </FieldGrid>

        {/* Dropzone drag & drop + pilih multiple */}
        <div
          role="button"
          tabIndex={queueOrPhotoFull || uploadProgress !== null ? -1 : 0}
          aria-disabled={queueOrPhotoFull || uploadProgress !== null}
          onClick={() => { if (!queueOrPhotoFull && uploadProgress === null) fileRef.current?.click(); }}
          onKeyDown={(e) => {
            if ((e.key === "Enter" || e.key === " ") && !queueOrPhotoFull && uploadProgress === null) {
              e.preventDefault();
              fileRef.current?.click();
            }
          }}
          onDragEnter={(e) => {
            e.preventDefault();
            e.stopPropagation();
            if (!queueOrPhotoFull && uploadProgress === null) setIsDragging(true);
          }}
          onDragOver={(e) => {
            e.preventDefault();
            e.stopPropagation();
            if (!queueOrPhotoFull && uploadProgress === null) setIsDragging(true);
          }}
          onDragLeave={(e) => {
            e.preventDefault();
            e.stopPropagation();
            setIsDragging(false);
          }}
          onDrop={handleDrop}
          className={`flex flex-col items-center justify-center gap-2 rounded-[22px] border-2 border-dashed px-6 py-7 text-center transition-colors ${
            queueOrPhotoFull || uploadProgress !== null
              ? "cursor-not-allowed border-admin-line bg-admin-surface/60 opacity-60"
              : isDragging
                ? "cursor-copy border-admin-ink bg-admin-surface"
                : "cursor-pointer border-admin-line-strong bg-admin-surface/50 hover:border-admin-ink/50 hover:bg-admin-surface"
          }`}
        >
          <span className="inline-flex size-11 items-center justify-center rounded-full bg-admin-canvas text-admin-ink shadow-xs">
            {uploadProgress ? (
              <Loader2 aria-hidden="true" size={20} className="animate-spin" />
            ) : (
              <UploadCloud aria-hidden="true" size={20} strokeWidth={1.5} />
            )}
          </span>
          <p className="text-[14px] font-medium text-admin-ink">
            {uploadProgress
              ? `Mengunggah ${uploadProgress.current} dari ${uploadProgress.total} foto…`
              : queueOrPhotoFull
                ? "Batas 20 foto sudah tercapai"
                : "Tarik & lepas beberapa foto ke sini, atau klik untuk memilih"}
          </p>
          <p className="text-[12px] text-admin-text-secondary">
            Bisa pilih banyak file sekaligus (JPEG, PNG, WebP · maks. 10 MiB/foto).
          </p>
          <p className="text-[11px] text-admin-text-secondary">
            Semua resolusi &amp; orientasi diperbolehkan (landscape maupun portrait) · disarankan minimal 1280×720 piksel.
          </p>
        </div>

        {activeQueue.length > 0 && (
          <div className="space-y-3 rounded-[20px] border border-admin-line-strong bg-admin-surface/70 p-4">
            <div className="flex flex-wrap items-center justify-between gap-3">
              <div className="space-y-0.5">
                <p className="text-[13px] font-semibold text-admin-ink">
                  Siap dikirim ({activeQueue.length} foto)
                </p>
                <p className="text-[12px] text-admin-text-secondary">
                  Foto disimpan sementara di cache browser dan otomatis terhapus jika modal ditutup atau halaman diganti. Klik Submit untuk menyimpan.
                </p>
              </div>
              <button
                type="button"
                disabled={uploadProgress !== null}
                onClick={clearQueuedPhotos}
                className="inline-flex h-9 items-center justify-center rounded-full border border-admin-line-strong bg-admin-canvas px-3.5 text-[12px] font-medium text-admin-ink transition-colors hover:bg-admin-surface disabled:opacity-50 cursor-pointer"
              >
                Kosongkan
              </button>
            </div>

            <div className="grid grid-cols-2 gap-3 sm:grid-cols-3 md:grid-cols-4">
              {activeQueue.map((item) => (
                <div
                  key={item.id}
                  className="group relative aspect-[4/3] overflow-hidden rounded-[16px] border border-admin-line bg-admin-canvas"
                >
                  {/* eslint-disable-next-line @next/next/no-img-element */}
                  <img src={item.previewUrl} alt={item.altText} className="size-full object-cover" />
                  <span className="absolute left-2 top-2 rounded-full bg-admin-canvas/90 px-2 py-0.5 text-[10px] font-medium text-admin-ink shadow-xs">
                    Belum dikirim
                  </span>
                  <button
                    type="button"
                    disabled={uploadProgress !== null}
                    onClick={() => removeQueuedPhoto(item.id)}
                    aria-label={`Batalkan ${item.file.name}`}
                    title="Hapus dari antrean"
                    className="absolute right-2 top-2 inline-flex size-7 items-center justify-center rounded-full bg-admin-canvas/90 text-admin-danger shadow-sm transition-colors hover:bg-admin-rose-soft disabled:opacity-50 cursor-pointer"
                  >
                    <X aria-hidden="true" size={14} />
                  </button>
                </div>
              ))}
            </div>
          </div>
        )}

        {uploadErrors.length > 0 && (
          <div role="alert" className="space-y-1 rounded-2xl bg-admin-rose-soft px-4 py-3 text-[12px] text-admin-danger">
            {uploadErrors.map((err, idx) => (
              <p key={idx}>{err}</p>
            ))}
          </div>
        )}

        {photos.length > 0 ? (
          <div className="space-y-3">
            <div className="flex flex-wrap items-center justify-between gap-2 rounded-2xl border border-admin-line bg-admin-surface/60 px-3.5 py-2.5">
              <div className="flex items-center gap-2.5">
                <button
                  type="button"
                  onClick={() => {
                    if (selectedPhotoIds.length === photos.length) {
                      setSelectedPhotoIds([]);
                    } else {
                      setSelectedPhotoIds(photos.map((p) => p.id));
                    }
                  }}
                  className="text-[12px] font-medium text-admin-ink underline underline-offset-4 hover:text-admin-text-secondary cursor-pointer"
                >
                  {selectedPhotoIds.length === photos.length ? "Batal pilih semua" : "Pilih semua foto"}
                </button>
                {selectedPhotoIds.length > 0 && (
                  <span className="text-[12px] text-admin-text-secondary">
                    · {selectedPhotoIds.length} terpilih
                  </span>
                )}
              </div>

              {selectedPhotoIds.length > 0 && (
                <div className="flex flex-wrap items-center gap-2">
                  <button
                    type="button"
                    disabled={uploadProgress !== null || isPending}
                    onClick={() => replaceMultiRef.current?.click()}
                    className="inline-flex h-8 items-center gap-1.5 rounded-full border border-admin-line-strong bg-admin-canvas px-3 text-[12px] font-medium text-admin-ink transition-colors hover:bg-admin-surface disabled:opacity-50 cursor-pointer"
                  >
                    <RefreshCw aria-hidden="true" size={13} />
                    <span>Ganti {selectedPhotoIds.length} foto</span>
                  </button>
                  <button
                    type="button"
                    disabled={uploadProgress !== null || isPending}
                    onClick={() => setConfirmMultiDelete(true)}
                    className="inline-flex h-8 items-center gap-1.5 rounded-full bg-admin-danger px-3 text-[12px] font-medium text-white transition-opacity hover:opacity-90 disabled:opacity-50 cursor-pointer"
                  >
                    <Trash2 aria-hidden="true" size={13} />
                    <span>Hapus {selectedPhotoIds.length} foto</span>
                  </button>
                </div>
              )}
            </div>

            <div className="grid grid-cols-2 gap-3 sm:grid-cols-3 md:grid-cols-4">
              {photos.map((photo) => {
                const isSelected = selectedPhotoIds.includes(photo.id);
                const version = replacedVersions[photo.id];
                const imgSrc = version ? `${photo.src}${photo.src.includes("?") ? "&" : "?"}v=${version}` : photo.src;
                return (
                  <div
                    key={photo.id}
                    className={`group relative aspect-[4/3] overflow-hidden rounded-[20px] border bg-admin-surface transition-all ${
                      isSelected ? "border-admin-ink ring-2 ring-admin-ink/30" : "border-admin-line"
                    }`}
                  >
                    {/* eslint-disable-next-line @next/next/no-img-element */}
                    <img src={imgSrc} alt={photo.alt} className="size-full object-cover" />
                    <button
                      type="button"
                      onClick={() => togglePhotoSelection(photo.id)}
                      aria-pressed={isSelected}
                      aria-label={`Pilih foto ${photo.alt || photo.id}`}
                      className={`absolute left-2 top-2 inline-flex size-7 items-center justify-center rounded-full border shadow-sm transition-colors cursor-pointer ${
                        isSelected
                          ? "border-admin-ink bg-admin-ink text-admin-on-ink"
                          : "border-admin-line bg-admin-canvas/90 text-transparent hover:border-admin-ink"
                      }`}
                    >
                      <Check aria-hidden="true" size={14} />
                    </button>
                    <div className="absolute right-2 top-2 flex items-center gap-1.5">
                      <button
                        type="button"
                        disabled={uploadProgress !== null || isPending}
                        onClick={() => {
                          setReplaceTargetId(photo.id);
                          replaceSingleRef.current?.click();
                        }}
                        aria-label={`Ganti foto ${photo.alt || photo.id}`}
                        title="Ganti foto"
                        className="inline-flex size-8 items-center justify-center rounded-full bg-admin-canvas/90 text-admin-ink shadow-sm transition-colors hover:bg-admin-surface disabled:opacity-50 cursor-pointer"
                      >
                        <RefreshCw aria-hidden="true" size={14} />
                      </button>
                      <button
                        type="button"
                        disabled={uploadProgress !== null || isPending}
                        onClick={() => setDeleteTarget(photo)}
                        aria-label={`Hapus foto ${photo.alt || photo.id}`}
                        title="Hapus foto"
                        className="inline-flex size-8 items-center justify-center rounded-full bg-admin-canvas/90 text-admin-danger shadow-sm transition-colors hover:bg-admin-rose-soft disabled:opacity-50 cursor-pointer"
                      >
                        <Trash2 aria-hidden="true" size={15} />
                      </button>
                    </div>
                  </div>
                );
              })}
            </div>
          </div>
        ) : (
          <p className="rounded-[20px] border border-dashed border-admin-line px-4 py-6 text-center text-[13px] text-admin-text-secondary">
            Belum ada foto dokumentasi untuk program ini.
          </p>
        )}
      </div>

      {/* Video YouTube */}
      <div className="space-y-4 border-t border-admin-line pt-6">
        <div className="flex flex-wrap items-center gap-2.5">
          <h3 className="text-[14px] font-semibold text-admin-ink">
            Video{" "}
            <span className={cap.videosBelowMin ? "text-admin-peach-ink" : "text-admin-text-secondary"}>
              {cap.videos} / {MAX_PROGRAM_VIDEOS}
            </span>
          </h3>
          {cap.videosBelowMin && (
            <span className="rounded-full bg-admin-peach-soft px-2.5 py-0.5 text-[12px] font-medium text-admin-peach-ink">
              Disarankan minimal 1 video
            </span>
          )}
        </div>

        {videos.length > 0 && (
          <ul className="space-y-3">
            {videos.map((video) => {
              const isEditingThis = editingVideo?.id === video.id;
              if (isEditingThis && editingVideo) {
                return (
                  <li
                    key={video.id}
                    className="space-y-4 rounded-[20px] border border-admin-line-strong bg-admin-surface/70 p-4 sm:p-5"
                  >
                    <div className="flex items-center justify-between gap-2">
                      <p className="text-[13px] font-semibold text-admin-ink">Edit video</p>
                      <button
                        type="button"
                        disabled={isPending}
                        onClick={() => {
                          setEditingVideo(null);
                          setVideoError(null);
                        }}
                        className="text-[12px] font-medium text-admin-text-secondary hover:text-admin-ink cursor-pointer"
                      >
                        Batal
                      </button>
                    </div>
                    <FieldGrid columns={1}>
                      <Field
                        label="URL YouTube"
                        htmlFor={`edit-video-url-${video.id}`}
                        hint={
                          editingVideo.fetching
                            ? "Mengambil judul dari YouTube…"
                            : editingVideo.title
                              ? `Judul YouTube: ${editingVideo.title}`
                              : "Gunakan tautan unlisted atau private. Judul diambil otomatis dari YouTube."
                        }
                      >
                        <AdminInput
                          id={`edit-video-url-${video.id}`}
                          type="url"
                          disabled={isPending}
                          value={editingVideo.url}
                          onChange={(e) => {
                            const nextUrl = e.target.value;
                            setEditingVideo((prev) =>
                              prev ? { ...prev, url: nextUrl, title: "", autoGenerated: true } : prev
                            );
                            scheduleEditTitleFetch(nextUrl, true);
                          }}
                          placeholder="https://youtu.be/..."
                        />
                      </Field>
                    </FieldGrid>
                    <div className="flex justify-end gap-2 pt-1">
                      <button
                        type="button"
                        disabled={isPending}
                        onClick={() => {
                          setEditingVideo(null);
                          setVideoError(null);
                        }}
                        className="inline-flex h-9 items-center justify-center rounded-full border border-admin-line-strong bg-admin-canvas px-4 text-[12px] font-medium text-admin-ink transition-colors hover:bg-admin-surface disabled:opacity-50 cursor-pointer"
                      >
                        Batal
                      </button>
                      <button
                        type="button"
                        disabled={isPending}
                        onClick={handleSaveEditedVideo}
                        className="inline-flex h-9 items-center justify-center gap-1.5 rounded-full bg-admin-ink px-4 text-[12px] font-medium text-admin-on-ink transition-colors hover:bg-admin-ink-soft disabled:opacity-50 cursor-pointer"
                      >
                        <span>{isPending ? "Menyimpan…" : "Simpan perubahan"}</span>
                      </button>
                    </div>
                  </li>
                );
              }

              return (
                <li
                  key={video.id}
                  className="flex items-center justify-between gap-3 rounded-[20px] border border-admin-line bg-admin-surface px-4 py-3"
                >
                  <div className="flex min-w-0 items-center gap-3">
                    <span className="inline-flex size-9 shrink-0 items-center justify-center rounded-full bg-admin-canvas text-admin-ink">
                      <Play aria-hidden="true" size={15} />
                    </span>
                    <div className="min-w-0">
                      <p className="truncate text-[14px] font-medium text-admin-ink">{video.alt}</p>
                      <p className="truncate text-[12px] text-admin-text-secondary">{video.src}</p>
                    </div>
                  </div>
                  <div className="flex shrink-0 items-center gap-1">
                    <button
                      type="button"
                      disabled={isPending}
                      onClick={() => {
                        setVideoError(null);
                        setEditingVideo({
                          id: video.id,
                          url: video.src,
                          title: video.alt,
                          autoGenerated: false,
                          fetching: false,
                        });
                      }}
                      aria-label={`Edit video ${video.alt}`}
                      title="Edit video"
                      className="inline-flex size-9 items-center justify-center rounded-full text-admin-ink transition-colors hover:bg-admin-surface-muted disabled:opacity-50 cursor-pointer"
                    >
                      <Pencil aria-hidden="true" size={15} />
                    </button>
                    <button
                      type="button"
                      disabled={isPending}
                      onClick={() => setDeleteTarget(video)}
                      aria-label={`Hapus video ${video.alt}`}
                      title="Hapus video"
                      className="inline-flex size-9 items-center justify-center rounded-full text-admin-danger transition-colors hover:bg-admin-rose-soft disabled:opacity-50 cursor-pointer"
                    >
                      <Trash2 aria-hidden="true" size={16} />
                    </button>
                  </div>
                </li>
              );
            })}
          </ul>
        )}

        {!cap.videoFull && (
          <div className="space-y-4">
            {visibleVideoDrafts.map((draft, idx) => (
              <div
                key={draft.id}
                className="space-y-4 rounded-[20px] border border-admin-line bg-admin-surface/50 p-4 sm:p-5"
              >
                <div className="flex items-center justify-between gap-2">
                  <p className="text-[13px] font-semibold text-admin-ink">
                    Video baru {visibleVideoDrafts.length > 1 ? `#${idx + 1}` : ""}
                  </p>
                  {visibleVideoDrafts.length > 1 && (
                    <button
                      type="button"
                      disabled={isPending}
                      onClick={() => handleRemoveVideoDraftRow(draft.id)}
                      aria-label={`Hapus form video #${idx + 1}`}
                      className="inline-flex items-center gap-1 text-[12px] font-medium text-admin-danger hover:underline cursor-pointer"
                    >
                      <X aria-hidden="true" size={14} />
                      <span>Hapus</span>
                    </button>
                  )}
                </div>
                <FieldGrid columns={1}>
                  <Field
                    label="URL YouTube"
                    htmlFor={`program-video-url-${draft.id}`}
                    hint={
                      draft.fetching
                        ? "Mengambil judul dari YouTube…"
                        : draft.title
                          ? `Judul YouTube: ${draft.title}`
                          : "Gunakan tautan unlisted atau private. Judul diambil otomatis dari YouTube."
                    }
                  >
                    <AdminInput
                      id={`program-video-url-${draft.id}`}
                      type="url"
                      disabled={isPending}
                      value={draft.url}
                      onChange={(e) => {
                        const nextUrl = e.target.value;
                        setVideoDrafts((prev) =>
                          prev.map((d) =>
                            d.id === draft.id ? { ...d, url: nextUrl, title: "", autoGenerated: true } : d
                          )
                        );
                        scheduleDraftTitleFetch(draft.id, nextUrl, true);
                      }}
                      placeholder="https://youtu.be/..."
                    />
                  </Field>
                </FieldGrid>
              </div>
            ))}

            {videoError && (
              <p role="alert" className="text-[12px] text-admin-danger">
                {videoError}
              </p>
            )}

            <div className="flex justify-start pt-1">
              <button
                type="button"
                disabled={isPending || visibleVideoDrafts.length >= cap.videoSlotsLeft}
                onClick={handleAddVideoDraftRow}
                className="inline-flex h-10 items-center justify-center gap-1.5 rounded-full border border-admin-line-strong bg-admin-canvas px-4 text-[13px] font-medium text-admin-ink transition-colors hover:bg-admin-surface disabled:cursor-not-allowed disabled:opacity-50 cursor-pointer"
              >
                <Plus aria-hidden="true" size={15} />
                <span>Tambah video</span>
              </button>
            </div>
          </div>
        )}

        {cap.videoFull && videoError && (
          <p role="alert" className="text-[12px] text-admin-danger">
            {videoError}
          </p>
        )}
      </div>

      <DeleteSheet
        open={deleteTarget !== null}
        onOpenChange={(open) => {
          if (!open) setDeleteTarget(null);
        }}
        title={deleteTarget?.kind === "image" ? "Hapus foto ini?" : `Hapus "${deleteTarget?.alt ?? "video"}"?`}
        successMessage={deleteTarget?.kind === "image" ? "Foto dihapus." : "Video dihapus."}
        onConfirm={confirmDelete}
      >
        <p className="text-[14px] text-admin-text-secondary">
          {deleteTarget?.kind === "image"
            ? "Foto akan dihapus dari galeri program dan penyimpanan."
            : "Tautan video YouTube akan dihapus dari dokumentasi program."}
        </p>
      </DeleteSheet>

      <DeleteSheet
        open={confirmMultiDelete}
        onOpenChange={setConfirmMultiDelete}
        title={`Hapus ${selectedPhotoIds.length} foto terpilih?`}
        confirmLabel="Hapus semua"
        successMessage={`${selectedPhotoIds.length} foto dihapus dari galeri dan penyimpanan.`}
        onConfirm={confirmMultiDeleteAction}
      >
        <p className="text-[14px] text-admin-text-secondary">
          Semua foto yang dipilih akan dihapus permanen dari galeri program dan penyimpanan.
        </p>
      </DeleteSheet>

      {!hideInlineSubmit && (
        <div className="border-t border-admin-line pt-5">
          <button
            type="submit"
            disabled={uploadProgress !== null || isPending}
            className="inline-flex h-12 w-full items-center justify-center rounded-full bg-admin-ink text-[15px] font-medium text-admin-on-ink transition-colors hover:bg-admin-ink-soft disabled:cursor-not-allowed disabled:opacity-50 cursor-pointer"
          >
            {uploadProgress || isPending ? "Menyimpan…" : "Submit"}
          </button>
        </div>
      )}

      <UploadBlockingModal
        open={uploadProgress !== null}
        title="Mengunggah foto program…"
        current={uploadProgress?.current}
        total={uploadProgress?.total}
      />
    </form>
  );
}
